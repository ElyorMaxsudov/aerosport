/**
 * Helper to get localized difficulty label
 */
export const getLocalizedDifficulty = (difficulty, lang = 'uz') => {
  if (!difficulty) return '';
  const item = difficultyTranslations[difficulty];
  if (item && item[lang]) return item[lang];

  // Reverse search if difficulty is in uz/ru/en
  const entry = Object.values(difficultyTranslations).find(
    (d) =>
      d.uz?.toLowerCase() === difficulty.toLowerCase() ||
      d.ru?.toLowerCase() === difficulty.toLowerCase() ||
      d.en?.toLowerCase() === difficulty.toLowerCase()
  );
  if (entry && entry[lang]) return entry[lang];
  return difficulty;
};

/**
 * Returns fully localized event object
 */
export const getLocalizedEvent = (event, lang = 'uz') => {
  if (!event) return null;

  // Find matching catalog entry by exact key or by any language title
  let catalogItem = eventCatalogTranslations[event.title];
  if (!catalogItem) {
    catalogItem = Object.values(eventCatalogTranslations).find(
      (item) =>
        item.title?.uz?.toLowerCase() === event.title?.toLowerCase() ||
        item.title?.ru?.toLowerCase() === event.title?.toLowerCase() ||
        item.title?.en?.toLowerCase() === event.title?.toLowerCase()
    );
  }

  const localizedTitle = catalogItem?.title?.[lang] || event.title;
  const localizedLocation = catalogItem?.location?.[lang] || event.location;
  const localizedCity = catalogItem?.city?.[lang] || event.city;
  const localizedCategory = catalogItem?.category?.[lang] || event.category;
  const localizedPrizePool = catalogItem?.prizePool?.[lang] || event.prizePool;
  const localizedDesc = catalogItem?.description?.[lang] || event.description;
  const localizedOrganizer = catalogItem?.organizer?.[lang] || event.organizer;
  const localizedDiff = getLocalizedDifficulty(catalogItem?.difficulty || event.difficulty, lang);

  return {
    ...event,
    title: localizedTitle,
    location: localizedLocation,
    city: localizedCity,
    category: localizedCategory,
    prizePool: localizedPrizePool,
    description: localizedDesc,
    organizer: localizedOrganizer,
    difficultyLabel: localizedDiff,
  };
};
