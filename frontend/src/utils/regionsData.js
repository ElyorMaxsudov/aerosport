export const getDistrictsByRegion = (regionName) => {
  const found = UZBEKISTAN_REGIONS.find(
    (r) => r.name.toLowerCase() === (regionName || '').toLowerCase()
  );
  return found ? found.districts : ['Markaziy tuman'];
};

