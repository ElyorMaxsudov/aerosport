/**
 * Returns a fully localized facility object for the given language (uz, ru, en)
 */
export const getLocalizedFacility = (facility, lang = 'uz') => {
  if (!facility) return null;

  // Find in catalog translations by exact name or translated name match
  let catalogItem = facilityCatalogTranslations[facility.name];
  if (!catalogItem) {
    catalogItem = Object.values(facilityCatalogTranslations).find(
      (item) =>
        item.name?.uz?.toLowerCase() === facility.name?.toLowerCase() ||
        item.name?.ru?.toLowerCase() === facility.name?.toLowerCase() ||
        item.name?.en?.toLowerCase() === facility.name?.toLowerCase()
    );
  }

  const localizedName = catalogItem?.name?.[lang] || facility.name;
  const localizedTitle = catalogItem?.title?.[lang] || facility.title;
  const localizedCity = catalogItem?.city?.[lang] || facility.city;
  const localizedAddress = catalogItem?.address?.[lang] || facility.address;
  const localizedDesc = catalogItem?.description?.[lang] || facility.description;

  // Localized surface
  const surfaceEntry = surfaceTranslations[facility.surface];
  const localizedSurface = surfaceEntry?.[lang] || facility.surface;

  // Localized type
  const typeEntry = facilityTypeTranslations[facility.type];
  const localizedTypeLabel = typeEntry?.[lang] || facility.type;

  // Localized amenities list
  const localizedAmenities = (facility.amenities || []).map((amenity) => {
    const entry = amenityTranslations[amenity];
    return entry?.[lang] || amenity;
  });

  return {
    ...facility,
    name: localizedName,
    title: localizedTitle,
    city: localizedCity,
    address: localizedAddress,
    description: localizedDesc,
    surface: localizedSurface,
    typeLabel: localizedTypeLabel,
    amenities: localizedAmenities,
  };
};
